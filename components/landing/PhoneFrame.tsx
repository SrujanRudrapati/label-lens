import Image from "next/image";
import type { CSSProperties, ReactNode } from "react";

interface PhoneFrameProps {
  /** Screen width in CSS pixels; the bezel, corners and island scale from it. */
  width: number;
  /** Screen aspect as "w / h". Screenshots are 390 / 844. */
  aspect?: string;
  className?: string;
  children: ReactNode;
}

/** A plain CSS phone: ink body, thin bezel, island, side buttons. Purely decorative around its screen. */
export function PhoneFrame({ width, aspect = "390 / 844", className = "", children }: PhoneFrameProps) {
  return (
    <div className={`phone-frame shrink-0 ${className}`} style={{ "--w": `${width}px` } as CSSProperties}>
      <div className="phone-screen" style={{ "--aspect": aspect } as CSSProperties}>
        <span aria-hidden="true" className="phone-island" />
        {children}
      </div>
    </div>
  );
}

export type ScreenId = "profile" | "home" | "first-read" | "result" | "evidence" | "ask";

interface PhoneShotProps {
  screen: ScreenId;
  alt: string;
  width: number;
  className?: string;
}

/** A real screenshot of the app (regenerated by scripts/landing-shots.mjs), lazy-loaded inside a frame. */
export function PhoneShot({ screen, alt, width, className }: PhoneShotProps) {
  return (
    <PhoneFrame width={width} className={className}>
      <Image src={`/landing/${screen}.webp`} alt={alt} width={780} height={1688} sizes={`${width}px`} loading="lazy" className="block size-full" />
    </PhoneFrame>
  );
}
